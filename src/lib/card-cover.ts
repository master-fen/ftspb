/**
 * Правило «маленькая обложка» — одно на все карточки новостей.
 *
 * Область обложки карточки на широком экране: контейнер публичной зоны 1280
 * (`mx-auto max-w-7xl lg:box-content`, поля снаружи `max-width`), лента — три
 * колонки с зазором 20 (`grid-cols-3 gap-5`), значит (1280 − 2×20) / 3 =
 * 413,33 по ширине; пропорция слота 4:3 (`COVER_RATIO`) даёт 310 по высоте.
 * Это самая маленькая из карточных областей: малые карточки «Главного» лежат
 * в такой же сетке, герой вдвое шире, миниатюра «Последнего» на узком экране
 * — 84×84. Порог берётся по самой маленькой: обложка, заполняющая её, не
 * увеличивается нигде.
 */
export const CARD_COVER_SLOT = { width: 413, height: 310 } as const;

/**
 * Допуск на увеличение. Маленькой считается не всякая обложка, которую надо
 * растянуть, а только та, которую надо растянуть больше чем на 15 %: обложка
 * 400×300 при растяжении на 3 % не портится, а показанная целиком легла бы с
 * полосами по 6 точек — это читается как ошибка вёрстки (решение Антона
 * 23.09.2026). Замер по локальной схеме `dev`: при нулевом допуске маленьких
 * 650 из 1636, при 15 % — 554; выпавшие 96 — почти все шириной ровно 400.
 */
export const CARD_COVER_UPSCALE_TOLERANCE = 1.15;

/**
 * Маленькая ли обложка: хотя бы одну сторону пришлось бы увеличить больше чем
 * на `CARD_COVER_UPSCALE_TOLERANCE`, чтобы заполнить область карточки.
 * Размеров нет (фото из админки, прошлые загрузки) или они бессмысленны —
 * обложка считается обычной и показывается как раньше.
 */
export function isSmallCover(
  width: number | null | undefined,
  height: number | null | undefined,
): boolean {
  if (
    typeof width !== "number" ||
    typeof height !== "number" ||
    !Number.isInteger(width) ||
    !Number.isInteger(height) ||
    width <= 0 ||
    height <= 0
  ) {
    return false;
  }
  return (
    width * CARD_COVER_UPSCALE_TOLERANCE < CARD_COVER_SLOT.width ||
    height * CARD_COVER_UPSCALE_TOLERANCE < CARD_COVER_SLOT.height
  );
}
